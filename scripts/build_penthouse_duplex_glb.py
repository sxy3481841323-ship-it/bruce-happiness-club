#!/usr/bin/env python3
"""
Assemble PH·01 Sunlit Two-Floor Penthouse Duplex (assets/models/penthouse_duplex.glb)
from Antigravity master architectural shell + DeepSeek-generated 2048px textures,
2D gallery/TV artworks, sunny sky cyclorama, and 5 concurrent 3D furniture modules.
"""

import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
OUT_GLB = os.path.join(REPO_ROOT, "assets", "models", "penthouse_duplex.glb")

sys.path.insert(0, SCRIPT_DIR)

from penthouse_kit.prim_lib import SceneContext
from penthouse_kit.tex_sky import make_sunny_sky_panorama
from penthouse_kit.tex_pbr import (
    make_herringbone_oak_tex,
    make_calacatta_marble_tex,
    make_boucle_fabric_tex,
    make_travertine_tex,
    make_fluted_walnut_tex,
    make_plush_rug_tex,
)
from penthouse_kit.tex_artworks import (
    make_tv_artworks,
    make_gallery_travel_artworks,
    make_vinyl_cover_tex,
)
from penthouse_kit.arch_shell import build_arch_shell
from penthouse_kit.mod_salon_seating import build_salon_seating
from penthouse_kit.mod_media_fireplace import build_media_fireplace
from penthouse_kit.mod_stair_balustrade import build_stair_and_balustrade
from penthouse_kit.mod_loft_2f import build_loft_2f
from penthouse_kit.mod_terrace_sky import build_terrace_and_sky


def build_duplex():
    ctx = SceneContext("PenthouseDuplex")

    # Textures generated by DeepSeek Batch 1
    oak_img = make_herringbone_oak_tex(2048)
    marble_img = make_calacatta_marble_tex(2048)
    boucle_img = make_boucle_fabric_tex(1024)
    travertine_img = make_travertine_tex(1024)
    walnut_fluted_img = make_fluted_walnut_tex(1024)
    rug_img = make_plush_rug_tex(1024)
    sky_sunny_img = make_sunny_sky_panorama(4096, 2048)
    tv_arts = make_tv_artworks()
    gal_arts = make_gallery_travel_artworks()
    vinyl_cover_img = make_vinyl_cover_tex(512)

    mats = {
        # Architectural PBR surfaces
        "oak": ctx.tex_mat("HerringboneOak", oak_img, roughness=0.42, metalness=0.04, quality=84),
        "marble": ctx.tex_mat("CalacattaGoldMarble", marble_img, roughness=0.18, metalness=0.04, quality=85),
        "walnut_fluted": ctx.tex_mat("FlutedWalnut", walnut_fluted_img, roughness=0.46, metalness=0.05, quality=84),
        "walnut_solid": ctx.color_mat("SolidWalnut", (0.28, 0.16, 0.10, 1.0), roughness=0.38, metalness=0.06),
        "plaster": ctx.color_mat("VenetianPlaster", (0.95, 0.92, 0.87, 1.0), roughness=0.72, metalness=0.02),
        "brass": ctx.color_mat("BrushedChampagneBrass", (0.85, 0.72, 0.45, 1.0), roughness=0.24, metalness=0.88),
        "chrome": ctx.color_mat("BrushedChrome", (0.86, 0.88, 0.91, 1.0), roughness=0.18, metalness=0.92),
        "warm_led": ctx.color_mat("WarmCoveLED", (1.0, 0.91, 0.74, 1.0), roughness=0.2, emissive=(0.95, 0.76, 0.46)),
        "warm_bulb": ctx.color_mat("ArcLampBulbMat", (1.0, 0.93, 0.78, 1.0), roughness=0.22, emissive=(0.82, 0.64, 0.36)),
        "fireplace_glow": ctx.color_mat("FireplaceFlame", (1.0, 0.64, 0.25, 1.0), roughness=0.35, emissive=(0.96, 0.48, 0.14)),
        "glass": ctx.color_mat("ClearTemperedGlass", (0.86, 0.94, 1.0, 0.08), roughness=0.06, metalness=0.10, alpha_blend=True, double_sided=True),
        "frosted_glass": ctx.color_mat("ReededFrostedGlass", (0.94, 0.96, 0.98, 0.46), roughness=0.35, metalness=0.05, alpha_blend=True, double_sided=True),
        # Soft furnishings
        "boucle": ctx.tex_mat("ItalianBoucle", boucle_img, roughness=0.88, metalness=0.0, quality=82),
        "travertine": ctx.tex_mat("RomanTravertine", travertine_img, roughness=0.36, metalness=0.03, quality=84),
        "rug": ctx.tex_mat("PlushWoolRug", rug_img, roughness=0.92, metalness=0.0, quality=82),
        "burgundy": ctx.color_mat("BurgundyVelvet", (0.42, 0.09, 0.14, 1.0), roughness=0.78, metalness=0.02),
        "cream_pillow": ctx.color_mat("CreamSilkLinen", (0.95, 0.91, 0.84, 1.0), roughness=0.76, metalness=0.02),
        "charcoal": ctx.color_mat("MatteCharcoal", (0.14, 0.14, 0.16, 1.0), roughness=0.45, metalness=0.20),
        "vinyl_black": ctx.color_mat("VinylRecord", (0.06, 0.06, 0.07, 1.0), roughness=0.16, metalness=0.25),
        "vinyl_cover": ctx.tex_mat("VinylCoverArt", vinyl_cover_img, roughness=0.42, metalness=0.02, quality=86),
        "tv_art": ctx.tex_mat("GalleryTVArtMat", tv_arts[0], roughness=0.26, metalness=0.02, quality=88, emissive=(0.14, 0.14, 0.14)),
        # Exterior terrace & greenery & sunny sky cyclorama
        "ceramic_white": ctx.color_mat("GlossCeramicWhite", (0.97, 0.96, 0.93, 1.0), roughness=0.18, metalness=0.04),
        "soil": ctx.color_mat("PottingSoil", (0.24, 0.18, 0.14, 1.0), roughness=0.95),
        "bark": ctx.color_mat("OliveBark", (0.42, 0.34, 0.27, 1.0), roughness=0.86),
        "olive_leaf": ctx.color_mat("OliveLeafDeep", (0.24, 0.42, 0.25, 1.0), roughness=0.74),
        "olive_leaf_bright": ctx.color_mat("OliveLeafSunlit", (0.38, 0.56, 0.34, 1.0), roughness=0.70),
        "sky_sunny": ctx.tex_mat("SkyCycloramaSunny", sky_sunny_img, roughness=1.0, metalness=0.0, quality=86, double_sided=True),
        # 2F Travel Gallery frames
        "gal_1": ctx.tex_mat("TravelGallery1", gal_arts[0], roughness=0.32, quality=86, emissive=(0.06, 0.06, 0.06)),
        "gal_2": ctx.tex_mat("TravelGallery2", gal_arts[1], roughness=0.32, quality=86, emissive=(0.06, 0.06, 0.06)),
        "gal_3": ctx.tex_mat("TravelGallery3", gal_arts[2], roughness=0.32, quality=86, emissive=(0.06, 0.06, 0.06)),
        "gal_4": ctx.tex_mat("TravelGallery4", gal_arts[3], roughness=0.32, quality=86, emissive=(0.06, 0.06, 0.06)),
    }

    build_arch_shell(ctx, mats)
    build_salon_seating(ctx, mats)
    build_media_fireplace(ctx, mats)
    build_stair_and_balustrade(ctx, mats)
    build_loft_2f(ctx, mats)
    build_terrace_and_sky(ctx, mats)

    info = ctx.export_glb(OUT_GLB)
    for req in ("SkyCyclorama", "GalleryTVScreen", "ArcLampBulb"):
        assert req in info["mesh_names"], f"Missing required mesh {req}"
    assert info["size_mb"] <= 15.0, f"GLB exceeds 15 MB cap: {info['size_mb']} MB"
    print(
        f"Built penthouse_duplex.glb: {info['size_mb']:.2f} MB, "
        f"{info['tris']:,} tris, {info['meshes']} meshes, "
        f"{info['materials']} mats, {info['textures']} texs"
    )
    return info


if __name__ == "__main__":
    build_duplex()
